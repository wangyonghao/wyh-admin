    public static final String DOT = ".";


    /**
     * 逗号 {@code ","}
     */
    public static final String COMMA = ",";


    /**
     * 冒号 {@code ":"}
     */
    public static final String COLON = ":";


    /**
     * 问号 {@code "?"}
     */
    public static final String QUESTION_MARK = "?";

    /**
     * 下划线 {@code "_"}
     */
    public static final String UNDERLINE = "_";



